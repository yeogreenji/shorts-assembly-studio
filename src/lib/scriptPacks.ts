/** 톤까지 같은 팩을 우선하고, 없으면 템플릿의 아무 팩을 씁니다. */
export function findPack(template: TemplateId, topic: string, tone: Tone): ScriptPack | null {
  const haystack = topic.toLowerCase();
  const candidates = PACKS.filter((pack) => pack.template === template);
  const matched = candidates.filter((pack) => pack.keywords.some((keyword) => haystack.includes(keyword.toLowerCase())));
  if (!matched.length) return null;
  return matched.find((pack) => pack.tone === tone) ?? matched[0] ?? null;
}

/** 팩을 다른 톤으로 열 때 — 첫 컷의 말투만 바꿔 씁니다(대본이 통째로 어색해지지 않게). */
export function toneHook(pack: ScriptPack, tone: Tone): string | null {
  if (pack.tone === tone) return null;
  const first = pack.cuts[0];
  if (!first) return null;
  if (tone === 'humor') return `${first.v.replace(/[.?]$/, '')}? 이거 고르고 후회하는 사람 많습니다.`;
  if (tone === 'empathy') return `${first.v.replace(/[.?]$/, '')}? 저도 이게 제일 어려웠어요.`;
  return `${first.v.replace(/[.?]$/, '')}? 결론부터 말합니다.`;
}
